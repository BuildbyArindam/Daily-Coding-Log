# Problem: CodeChef Round - CODECHEF
# Link: https://www.codechef.com/problems/CODECHEF
# Date: 2026-09-02
# Difficulty: Cakewalk
# Topics: Basic I/O, Conditional Statements, Implementation
# Approach: Read integer N; output "YES" if N == 4, else "NO" — direct
#           conditional check against the target value, no preprocessing needed.
# Time Complexity: O(1)
# Space Complexity: O(1)


# -------------------------- Solution ----------------------------


N = int(input())
if N == 4:
    print("YES")
else:
    print("NO")
